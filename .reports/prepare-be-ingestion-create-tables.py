def stage(relative, transform):
    target = BE / relative
    raw = target.read_bytes() if target.exists() else None
    text = raw.decode('utf-8-sig').replace('\r\n', '\n') if raw else ''
    result = transform(text)
    dest = STAGE / relative
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(result, encoding='utf-8')
    manifest.append({'target': str(target), 'stage': str(dest),
        'sha256': hashlib.sha256(raw).hexdigest() if raw is not None else None})


def new_sql(relative, content):
    def transform(old):
        assert not old, relative
        return content
    stage(MIG + relative, transform)


