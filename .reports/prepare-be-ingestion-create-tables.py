def split_fields(text):
    fields, start, depth, quote, i = [], 0, 0, None, 0
    while i < len(text):
        c = text[i]
        if quote:
            if c == '\\':
                i += 2
                continue
            if c == quote:
                if i + 1 < len(text) and text[i + 1] == quote:
                    i += 2
                    continue
                quote = None
        elif c in "'\"`":
            quote = c
        elif text.startswith('--', i) and (i + 2 == len(text) or text[i + 2].isspace()):
            newline = text.find('\n', i)
            i = len(text) if newline < 0 else newline + 1
            continue
        elif text.startswith('/*', i):
            close = text.find('*/', i + 2)
            assert close >= 0
            i = close + 2
            continue
        elif c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
        elif c == ',' and depth == 0:
            fields.append(text[start:i])
            start = i + 1
        i += 1
    assert quote is None and depth == 0
    fields.append(text[start:])
    return fields


def statement_end(text, start):
    quote, i = None, start
    while i < len(text):
        c = text[i]
        if quote:
            if c == '\\':
                i += 2
                continue
            if c == quote:
                if i + 1 < len(text) and text[i + 1] == quote:
                    i += 2
                    continue
                quote = None
        elif c in "'\"`":
            quote = c
        elif text.startswith('--', i) and (i + 2 == len(text) or text[i + 2].isspace()):
            newline = text.find('\n', i)
            i = len(text) if newline < 0 else newline + 1
            continue
        elif text.startswith('/*', i):
            close = text.find('*/', i + 2)
            assert close >= 0
            i = close + 2
            continue
        elif c == ';':
            return i
        i += 1
    raise ValueError('Unterminated seed statement')


def seed(s):
    pattern = r'INSERT INTO `material_chunks`\s*\((.*?)\)\s*VALUES\s*'
    matches = list(re.finditer(pattern, s, re.S | re.I))
    assert len(matches) == 1
    match = matches[0]
    columns = [c.strip().strip('`') for c in match[1].split(',')]
    material_pos = columns.index('material_id')
    end = statement_end(s, match.end())
    tuples = split_fields(s[match.end():end])
    revised = []
    for row in tuples:
        row = row.strip()
        prefix = ''
        while row.startswith('--'):
            comment, row = row.split('\n', 1)
            prefix += comment + '\n'
            row = row.lstrip()
        assert row.startswith('(') and row.endswith(')'), 'Unexpected seed tuple format'
        fields = split_fields(row[1:-1])
        assert len(fields) == len(columns), 'Seed field count mismatch'
        material_id = fields[material_pos].strip()
        revised.append(prefix + row[:-1] + ',\n    (SELECT v.id FROM material_versions v '
            f'WHERE v.material_id = {material_id} AND v.version_number = 1))')
    header = 'INSERT INTO `material_chunks` (\n' + match[1].strip() + ',\n    `material_version_id`\n) VALUES\n'
    prefix = '''-- Imported seed fixtures are unverified: no fabricated source hash/snapshot or teacher approval.
-- No material_publications row is created; publish only through the reviewed workflow.
INSERT INTO material_versions (
    id, material_id, version_number, source_hash, source_snapshot_url,
    parser_version, chunker_version, created_by
)
SELECT UNHEX(REPLACE(UUID(), '-', '')), m.id, 1, NULL, NULL,
       'seed-fixture', 'seed-fixture', m.uploaded_by
FROM materials m;

'''
    print(f'Prepared version links for {len(revised)} seed chunks (no row contents printed).')
    return s[:match.start()] + prefix + header + ',\n'.join(revised) + s[end:]


